-- PGRECON_OBJECT TABLE RECON_TEST.EMP

  CREATE TABLE "RECON_TEST"."EMP"
   (	"EMPNO" NUMBER(4,0),
	"ENAME" VARCHAR2(10) NOT NULL ENABLE,
	"JOB" VARCHAR2(9),
	"MGR" NUMBER(4,0),
	"HIREDATE" DATE DEFAULT SYSDATE,
	"SAL" NUMBER(7,2),
	"COMM" NUMBER(7,2),
	"DEPTNO" NUMBER(2,0),
	 CONSTRAINT "CK_EMP_SAL" CHECK (sal > 0) ENABLE,
	 CONSTRAINT "PK_EMP" PRIMARY KEY ("EMPNO")
  USING INDEX  ENABLE,
	 CONSTRAINT "FK_EMP_DEPT" FOREIGN KEY ("DEPTNO")
	  REFERENCES "RECON_TEST"."DEPT" ("DEPTNO") ENABLE,
	 CONSTRAINT "FK_EMP_MGR" FOREIGN KEY ("MGR")
	  REFERENCES "RECON_TEST"."EMP" ("EMPNO") ENABLE
   ) ;

-- PGRECON_OBJECT TABLE RECON_TEST.INVOICES

  CREATE TABLE "RECON_TEST"."INVOICES"
   (	"INVOICE_ID" NUMBER GENERATED ALWAYS AS IDENTITY MINVALUE 1 MAXVALUE 9999999999999999999999999999 INCREMENT BY 1 START WITH 1 CACHE 20 NOORDER  NOCYCLE  NOKEEP  NOSCALE  NOT NULL ENABLE,
	"CUSTOMER" VARCHAR2(100) NOT NULL ENABLE,
	"NET_AMOUNT" NUMBER(12,2) NOT NULL ENABLE,
	"VAT_RATE" NUMBER(4,2) DEFAULT 19,
	"GROSS" NUMBER(14,2) GENERATED ALWAYS AS (ROUND("NET_AMOUNT"*(1+"VAT_RATE"/100),2)) VIRTUAL ,
	"CREATED_AT" TIMESTAMP (6) WITH LOCAL TIME ZONE DEFAULT SYSTIMESTAMP,
	 CONSTRAINT "PK_INVOICES" PRIMARY KEY ("INVOICE_ID")
  USING INDEX  ENABLE
   ) ;

